# Las mayúsculas con tilde no se usan en los textos de fábrica, pero el usuario
# puede escribirlas en una etiqueta. Se sustituyen por la letra sin tilde: a 7
# px de alto no hay sitio para la tilde sin comerse la línea de arriba.
FOLD = {'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ü': 'U', 'Ñ': 'N'}

def glyph(ch):
    ch = FOLD.get(ch, ch)
    return G.get(ch, G['?'])

def rows9(ch):
    """Glifo normalizado a 9 filas (7 + 2 de rabo)."""
    rows = glyph(ch)
    w = max((len(r) for r in rows), default=0)
    out = [r.ljust(w, '.') for r in rows] + ['.' * w] * (9 - len(rows))
    return out[:9]

def width(ch):
    return len(rows9(ch)[0])

def text_width(s, gap=1):
    if not s:
        return 0
    return sum(width(c) for c in s) + gap * (len(s) - 1)

# --- Tamaño grande ----------------------------------------------------------------
# Para las pantallas que solo llevan texto. Es la misma fuente pasada por EPX
# (Scale2x): dobla el trazo a 2 px y rellena el escalón de las diagonales, que
# un simple doblado de píxeles dejaría en sierra.
#
# Con una diferencia respecto al EPX de libro: aquí solo puede encender
# píxeles, nunca apagarlos. El original también redondea las esquinas
# convexas, y en una fuente eso convierte la D en una O y la E en una C.
def epx(rows):
    h, w = len(rows), len(rows[0]) if rows else 0
    px = lambda x, y: rows[y][x] == '#' if 0 <= x < w and 0 <= y < h else False
    out = [['.'] * (2 * w) for _ in range(2 * h)]
    for y in range(h):
        for x in range(w):
            P = px(x, y)
            A, B, C, D = px(x, y - 1), px(x + 1, y), px(x - 1, y), px(x, y + 1)
            p1 = p2 = p3 = p4 = P
            if C == A and C != D and A != B: p1 = A
            if A == B and A != C and B != D: p2 = B
            if D == C and D != B and C != A: p3 = C
            if B == D and B != A and D != C: p4 = D
            for (dx, dy, v) in ((0, 0, p1), (1, 0, p2), (0, 1, p3), (1, 1, p4)):
                out[2 * y + dy][2 * x + dx] = '#' if (v or P) else '.'
    return [''.join(r) for r in out]

